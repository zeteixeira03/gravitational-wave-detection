"""P2 analysis: empirical prior, theta-hat distributions, missing-physics check.

Inputs: outputs of gwsciml.detect.run_p1 on the train and val packed subsets
(per-sample CSV and likelihood maps) and the bank file.
Writes reports/P2_report.md, reports/figures/p2_*.png, and one row per scored
statistic to results/runs.jsonl.

Usage: python -m gwsciml.pe.p2_analysis --bank data/bank/<name>.npz --tag <tag>
"""

import argparse
import json
import subprocess
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from gwsciml.detect.run_p1 import auc_with_ci
from gwsciml.pe.prior import fit_joint_prior, fit_prior, log_lambda, log_lambda_joint
from gwsciml.templates.waveforms import chirp_mass


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bank", type=Path, required=True)
    ap.add_argument("--tag", required=True)
    ap.add_argument("--results", type=Path, default=Path("data/results"))
    ap.add_argument("--out", type=Path, default=Path("reports"))
    args = ap.parse_args()
    figs = args.out / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    params = np.load(args.bank)["params"]
    mc = chirp_mass(params[:, 0], params[:, 1])
    q = params[:, 1] / params[:, 0]
    tr = pd.read_csv(args.results / f"p1_train_{args.tag}.csv")
    va = pd.read_csv(args.results / f"p1_val_{args.tag}.csv")
    ltr = np.load(args.results / f"p1_train_{args.tag}_lmap.npy", mmap_mode="r")
    lva = np.load(args.results / f"p1_val_{args.tag}_lmap.npy", mmap_mode="r")
    lines = []

    def say(s=""):
        print(s)
        lines.append(s)

    say("# P2 report: unsupervised parameter estimation and empirical prior")
    say()
    say("Generated by `python -m gwsciml.pe.p2_analysis`. Train = packed train subset, val = packed")
    say("val subset (ROADMAP split). Every prior is fitted on train only and evaluated on val.")
    say()

    # ------------------------------------------------------------- (a) empirical prior
    pos = tr.target.values == 1
    log_pi, log_tau, trace = fit_prior(ltr[np.nonzero(pos)[0]], verbose=True)
    J, B = ltr.shape[1:]
    uni = (np.full(J, -np.log(J)), np.full(B, -np.log(B)))
    rows = {}
    for name, lp, lt in [("uniform", *uni), ("template prior", log_pi, uni[1]), ("time prior", uni[0], log_tau),
                         ("template x time prior", log_pi, log_tau)]:
        s_va = log_lambda(lva, lp, lt)
        rows[name] = auc_with_ci(va.target.values, s_va)
        if name == "template x time prior":
            va["lse_prior"] = s_va
    for a in (0.1, 1.0, 10.0):
        log_pj, _ = fit_joint_prior(ltr[np.nonzero(pos)[0]], alpha=a)
        rows[f"joint template-time prior, alpha {a:g}"] = auc_with_ci(va.target.values, log_lambda_joint(lva, log_pj))
    say("## (a) Empirical-Bayes prior (EM on train positives)")
    say()
    say(f"EM: {len(trace)} iterations, mean log Lambda on train positives {trace[0]:.4f} -> {trace[-1]:.4f}.")
    say()
    say("| statistic on val | AUC | bootstrap sd |")
    say("|---|---|---|")
    for k, (a, sd) in rows.items():
        say(f"| log Lambda, {k} | {a:.4f} | {sd:.4f} |")
    for k in ["inc_max", "inc_lse", "coh_max", "rw_net2"]:
        a, sd = auc_with_ci(va.target.values, va[k].values)
        say(f"| P1 {k} | {a:.4f} | {sd:.4f} |")
    say()
    pi, tau = np.exp(log_pi), np.exp(log_tau)
    t_cent = 0.1 + (np.arange(B) + 0.5) * (1.8 / B)
    fig, ax = plt.subplots(1, 3, figsize=(14, 4))
    ax[0].bar(t_cent, tau, width=1.8 / B * 0.9)
    ax[0].set(xlabel="H1 merger time [s]", ylabel="tau_b", title="fitted time prior")
    sc = ax[1].scatter(params[:, 0], params[:, 1], c=np.log10(pi * J), s=12, cmap="viridis")
    plt.colorbar(sc, ax=ax[1], label="log10(pi_j * J)")
    ax[1].set(xlabel="m1 [Msun]", ylabel="m2 [Msun]", title="fitted template prior")
    order = np.argsort(mc)
    ax[2].plot(mc[order], np.cumsum(pi[order]), label="fitted prior")
    ax[2].plot(mc[order], np.arange(1, J + 1) / J, label="uniform over bank")
    ax[2].set(xlabel="chirp mass [Msun]", ylabel="cumulative weight", title="prior mass in chirp mass")
    ax[2].legend()
    fig.tight_layout()
    fig.savefig(figs / "p2_prior.png", dpi=120)
    plt.close(fig)
    say("![prior](figures/p2_prior.png)")
    say()
    say(f"Time prior: {tau[t_cent > 1.4].sum():.3f} of the weight lies at H1 merger times > 1.4 s.")
    say(f"Template prior: weighted median chirp mass {mc[order][np.searchsorted(np.cumsum(pi[order]), 0.5)]:.1f} Msun")
    say(f"(uniform-over-bank median {np.median(mc):.1f} Msun).")
    say()

    # ------------------------------------------------------------- theta-hat distributions
    say("## theta-hat: maximum-likelihood point estimates")
    say()
    say("theta-hat = (template, H1 merger time, sky) of the largest coherent statistic. For")
    say("negatives it is pure noise fitting, so the contrast with positives shows which parameters")
    say("the data constrain. `loud` = val positives with coh_max above the 99th percentile of val negatives.")
    say()
    thr = np.percentile(va.coh_max[va.target == 0], 99)
    loud = va[(va.target == 1) & (va.coh_max > thr)]
    say(f"Threshold coh_max = {thr:.1f}; loud positives: {len(loud)} of {int(va.target.sum())} "
        f"({len(loud) / va.target.sum():.3f}).")
    say()
    fig, ax = plt.subplots(2, 3, figsize=(15, 8))
    groups = [("negatives", va[va.target == 0]), ("loud positives", loud)]
    for name, g in groups:
        ax[0, 0].hist(g.t_h1, bins=60, range=(0.1, 1.9), density=True, alpha=0.6, label=name)
        ax[0, 1].hist(mc[g.tmpl], bins=40, density=True, alpha=0.6, label=name)
        ax[0, 2].hist(q[g.tmpl], bins=30, range=(0, 1), density=True, alpha=0.6, label=name)
        ax[1, 0].hist(g.dt_L * 1e3, bins=60, range=(-14, 14), density=True, alpha=0.6, label=name)
        ax[1, 1].hist(g.dt_V * 1e3, bins=60, range=(-32, 32), density=True, alpha=0.6, label=name)
    ax[0, 0].set(xlabel="H1 merger time [s]")
    ax[0, 1].set(xlabel="chirp mass [Msun]")
    ax[0, 2].set(xlabel="mass ratio m2/m1")
    ax[1, 0].set(xlabel="t_L1 - t_H1 [ms]")
    ax[1, 1].set(xlabel="t_V1 - t_H1 [ms]")
    for name, g in groups:
        ax[1, 2].scatter(np.sqrt(g.rho_H ** 2 + g.rho_L ** 2), (g.chi2r_H + g.chi2r_L) / 2, s=3, alpha=0.4, label=name)
    ax[1, 2].set(xlabel="sqrt(rho_H^2 + rho_L^2)", ylabel="mean reduced chi2 (H1, L1)", yscale="log")
    for a in ax.ravel():
        a.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(figs / "p2_theta_hat.png", dpi=120)
    plt.close(fig)
    say("![theta-hat](figures/p2_theta_hat.png)")
    say()
    say("| quantity | negatives median (IQR) | loud positives median (IQR) |")
    say("|---|---|---|")

    def iqr(v):
        return f"{np.median(v):.3g} ({np.percentile(v, 25):.3g}-{np.percentile(v, 75):.3g})"
    for label, f in [("H1 merger time [s]", lambda g: g.t_h1), ("chirp mass [Msun]", lambda g: mc[g.tmpl]),
                     ("mass ratio", lambda g: q[g.tmpl]), ("abs(t_L1 - t_H1) [ms]", lambda g: np.abs(g.dt_L) * 1e3),
                     ("abs(t_V1 - t_H1) [ms]", lambda g: np.abs(g.dt_V) * 1e3),
                     ("rho_H", lambda g: g.rho_H), ("rho_L", lambda g: g.rho_L), ("rho_V", lambda g: g.rho_V),
                     ("null energy at coherent max", lambda g: g.null_at_coh),
                     ("chi2_r H1", lambda g: g.chi2r_H), ("chi2_r L1", lambda g: g.chi2r_L)]:
        say(f"| {label} | {iqr(f(groups[0][1]))} | {iqr(f(loud))} |")
    say()

    # ------------------------------------------------------------- missing physics
    say("## Missing-physics check (template-family mismatch)")
    say()
    say("If the true signals are in the bank's family (non-spinning IMRPhenomD), the Allen chi2 of")
    say("a loud signal stays near 1 (chi2 with 2p-2 dof divided by its dof). A mismatch 1 - m between")
    say("signal and best template adds about rho^2 (1 - m) x O(1) to chi2 (the residual power that")
    say("the template does not absorb is distributed across bands), so chi2_r grows with rho^2.")
    say()
    say("| rho_H1,L1 bin | n | median chi2_r H1 | median chi2_r L1 | median null energy |")
    say("|---|---|---|---|---|")
    vp = va[va.target == 1].copy()
    vp["rho_hl"] = np.sqrt(vp.rho_H ** 2 + vp.rho_L ** 2)
    for lo, hi in [(0, 8), (8, 12), (12, 16), (16, 24), (24, 40), (40, 200)]:
        g = vp[(vp.rho_hl >= lo) & (vp.rho_hl < hi)]
        if len(g):
            say(f"| {lo}-{hi} | {len(g)} | {g.chi2r_H.median():.2f} | {g.chi2r_L.median():.2f} | {g.null_at_coh.median():.2f} |")
    g = va[va.target == 0]
    say(f"| negatives | {len(g)} | {g.chi2r_H.median():.2f} | {g.chi2r_L.median():.2f} | {g.null_at_coh.median():.2f} |")
    say()
    (args.out / "P2_report.md").write_text("\n".join(lines) + "\n")

    git = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    with open("results/runs.jsonl", "a") as fh:
        fh.write(json.dumps({
            "time": time.strftime("%Y-%m-%dT%H:%M:%S"), "phase": "P2a", "git": git, "split": "val",
            "n": int(len(va)), "bank": args.bank.name, "tag": args.tag, "prior_fit": "MAP-EM on train positives",
            "n_train_pos": int(pos.sum()), "em_iterations": len(trace),
            "auc": {k: v[0] for k, v in rows.items()}, "auc_bootstrap_sd": {k: v[1] for k, v in rows.items()},
        }) + "\n")
    np.savez(args.results / f"p2_prior_{args.tag}.npz", log_pi=log_pi, log_tau=log_tau)


if __name__ == "__main__":
    main()
