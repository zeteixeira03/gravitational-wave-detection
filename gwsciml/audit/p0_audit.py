"""P0 data audit. Writes reports/P0_audit.md and reports/figures/p0_*.png.

Every test statistic is compared with its value on simulated stationary
Gaussian noise that has the measured average PSD and passes through the same
estimator. So "spread" and "non-Gaussianity" below always mean *excess over
the stationary-Gaussian expectation*, not raw scatter.

Usage: python -m gwsciml.audit.p0_audit --packed data/g2net/packed
"""

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import stats

from gwsciml.constants import DETECTORS, DT, FS, N
from gwsciml.data.io import load_packed
from gwsciml.data.psd import colored_noise, periodogram_psd, tukey, welch_psd, whiten
from gwsciml.data.split import load_labels

BANDS = [(20, 40), (40, 80), (80, 160), (160, 320), (320, 640), (640, 1000)]
WHITEN_BAND = (20.0, 1000.0)


def band_log_power(f, P, bands=BANDS):
    """log of the mean PSD in each band: (..., n_bands)."""
    return np.stack([np.log(P[..., (f >= a) & (f < b)].mean(axis=-1)) for a, b in bands], axis=-1)


def whitened_flat(x, psd, w):
    y = whiten(x, psd, w, band=WHITEN_BAND)
    frac = ((np.fft.rfftfreq(N, DT) >= WHITEN_BAND[0]) & (np.fft.rfftfreq(N, DT) <= WHITEN_BAND[1])).sum() / (N / 2)
    return y[..., w == 1.0] / np.sqrt(frac)   # unit variance for stationary Gaussian noise


def gaussianity(y):
    """Per sample and detector: excess kurtosis and max |y| (y has unit variance under H0)."""
    return stats.kurtosis(y, axis=-1), np.abs(y).max(axis=-1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--packed", type=Path, default=Path("data/g2net/packed"))
    ap.add_argument("--labels", type=Path, default=Path("data/g2net"))
    ap.add_argument("--out", type=Path, default=Path("reports"))
    args = ap.parse_args()
    figs = args.out / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(0)
    lines = []

    def say(s=""):
        print(s)
        lines.append(s)

    # ---------------------------------------------------------------- class balance
    df = load_labels(args.labels)
    say("# P0 audit: G2Net raw data")
    say()
    say("Generated by `python -m gwsciml.audit.p0_audit`. All numbers are recomputable from the")
    say("packed subset (kernel `gwsciml/kaggle/pack_subset`) and `training_labels.csv`.")
    say()
    say("## 1. Split and class balance (full label file)")
    say()
    say("| split | rows | positive fraction |")
    say("|---|---|---|")
    for split in ("val", "train"):
        d = df[df.split == split]
        say(f"| {split} | {len(d)} | {d.target.mean():.5f} |")
    say(f"| all | {len(df)} | {df.target.mean():.5f} |")
    say()

    xtr, mtr = load_packed(args.packed, "train", mmap=False)
    xva, mva = load_packed(args.packed, "val", mmap=False)
    ytr, yva = mtr.target.values, mva.target.values
    say(f"Audit subset: {len(xtr)} train ({ytr.mean():.3f} positive), {len(xva)} val ({yva.mean():.3f} positive),")
    say("drawn class-balanced with seed 0 from each split. Raw float64 strain, shape (3, 4096) per sample.")
    say()

    # ---------------------------------------------------------------- average PSD
    w = tukey(N, 0.1)
    f = np.fft.rfftfreq(N, DT)
    neg_tr = xtr[ytr == 0]
    psd_avg = periodogram_psd(neg_tr, w).mean(axis=0)                  # (3, F)
    psd_val = periodogram_psd(xva[yva == 0], w).mean(axis=0)
    np.save(args.packed / "psd_avg_train_neg_tukey0.1.npy", psd_avg)
    say("## 2. Average noise PSD")
    say()
    say(f"Estimator: periodogram through Tukey(0.1), averaged over the {len(neg_tr)} train negatives")
    say("(leakage-inclusive by construction, see `gwsciml/data/psd.py`). Saved as")
    say("`data/g2net/packed/psd_avg_train_neg_tukey0.1.npy`.")
    say()
    say("| detector | ASD 12 Hz | ASD 20 Hz | ASD 50 Hz | ASD 100 Hz | ASD 200 Hz | ASD 500 Hz | val/train PSD ratio 20-500 Hz (mean, max dev) |")
    say("|---|---|---|---|---|---|---|---|")
    for k, d in enumerate(DETECTORS):
        a = [np.sqrt(psd_avg[k][np.argmin(np.abs(f - q))]) for q in (12, 20, 50, 100, 200, 500)]
        sel = (f >= 20) & (f <= 500)
        r = psd_val[k][sel] / psd_avg[k][sel]
        r4 = r[: (len(r) // 8) * 8].reshape(-1, 8).mean(axis=1)  # 4 Hz groups
        say(f"| {d} | " + " | ".join(f"{v:.2e}" for v in a) + f" | {r.mean():.4f}, {np.abs(r4 - 1).max():.3f} |")
    say()
    say("The val/train ratio uses 4 Hz groups (32 periodogram bins x ~2,500 samples each), so the")
    say("expected sampling scatter is about 0.4 %. Larger deviations would mean the two splits")
    say("do not share one noise model.")
    say()
    fig, ax = plt.subplots(figsize=(7, 4))
    for k, d in enumerate(DETECTORS):
        ax.loglog(f[1:], np.sqrt(psd_avg[k][1:]), label=d)
    ax.set(xlabel="frequency [Hz]", ylabel="ASD [1/sqrt(Hz)]", title="Average noise ASD (train negatives)")
    ax.axvspan(20, 1000, color="0.9", zorder=0)
    ax.legend()
    fig.tight_layout()
    fig.savefig(figs / "p0_asd.png", dpi=120)
    plt.close(fig)
    say("![ASD](figures/p0_asd.png)")
    say()

    # ---------------------------------------------------------------- per-sample PSD spread
    fw, Pw = welch_psd(neg_tr)                                          # (n, 3, Fw)
    lp = band_log_power(fw, Pw)                                          # (n, 3, B)
    n_sim = 2000
    sim = np.stack([colored_noise(psd_avg[k] * 1.0, n_sim, rng) for k in range(3)], axis=1)
    fs_, Ps = welch_psd(sim)
    lps = band_log_power(fs_, Ps)
    say("## 3. Per-sample PSD variation")
    say()
    say("Statistic: log of the per-sample Welch PSD (Hann, 0.5 s segments, 50 % overlap) averaged")
    say("in octave-like bands. `sd data` is its standard deviation over train negatives; `sd H0` is the")
    say("same on simulated stationary Gaussian noise with the average PSD. Note the simulation draws")
    say("from the leakage-inclusive average PSD without a window, so its Welch estimate is very")
    say("slightly different in level; the comparison is about spread, not level.")
    say("`excess sd` = sqrt(sd_data^2 - sd_H0^2) is the genuine sample-to-sample PSD variation.")
    say()
    say("| detector | band [Hz] | sd data | sd H0 | excess sd | excess as factor on PSD |")
    say("|---|---|---|---|---|---|")
    excess = np.zeros((3, len(BANDS)))
    for k, d in enumerate(DETECTORS):
        for b, (lo, hi) in enumerate(BANDS):
            sd_d, sd_s = lp[:, k, b].std(), lps[:, k, b].std()
            ex = np.sqrt(max(sd_d ** 2 - sd_s ** 2, 0.0))
            excess[k, b] = ex
            say(f"| {d} | {lo}-{hi} | {sd_d:.4f} | {sd_s:.4f} | {ex:.4f} | x{np.exp(ex):.3f} |")
    say()
    # structure of the variation: common scale across bands? across detectors?
    c = lp - lp.mean(axis=0)
    corr_bands = np.mean([np.corrcoef(c[:, k, :].T)[np.triu_indices(len(BANDS), 1)].mean() for k in range(3)])
    corr_det = np.corrcoef(c[:, :, 2].T)                                 # 80-160 Hz band
    cs = lps - lps.mean(axis=0)
    corr_bands_sim = np.mean([np.corrcoef(cs[:, k, :].T)[np.triu_indices(len(BANDS), 1)].mean() for k in range(3)])
    say(f"Mean correlation of the band log-powers across bands, within a detector: {corr_bands:.3f}")
    say(f"(H0 simulation: {corr_bands_sim:.3f}). Correlation between detectors in the 80-160 Hz band:")
    say(f"H1-L1 {corr_det[0, 1]:.3f}, H1-V1 {corr_det[0, 2]:.3f}, L1-V1 {corr_det[1, 2]:.3f}.")
    say()
    fig, axes = plt.subplots(1, 3, figsize=(12, 3.5), sharey=True)
    for k, d in enumerate(DETECTORS):
        axes[k].hist(c[:, k, 2], bins=60, density=True, alpha=0.6, label="data")
        axes[k].hist(cs[:, k, 2], bins=60, density=True, alpha=0.6, label="H0 sim")
        axes[k].set(title=f"{d}: log band power 80-160 Hz", xlabel="deviation from mean")
    axes[0].legend()
    fig.tight_layout()
    fig.savefig(figs / "p0_psd_spread.png", dpi=120)
    plt.close(fig)
    say("![PSD spread](figures/p0_psd_spread.png)")
    say()

    # per-bin test: periodogram of stationary Gaussian noise is chi2(2)/2 x S, so its squared
    # coefficient of variation cv^2 = var/mean^2 is 1 in every bin, whatever the PSD shape.
    from scipy.ndimage import median_filter
    Pn = periodogram_psd(neg_tr[:3000], w)
    cv2 = Pn.var(axis=0) / Pn.mean(axis=0) ** 2
    sel = (f >= 20) & (f <= 1000)
    n_cv = len(Pn)
    say("### 3b. Per-frequency-bin test and spectral lines")
    say()
    say("A bin-resolved test avoids band averaging. For stationary Gaussian noise the periodogram")
    say(f"in each bin is S_k x chi2(2)/2, so cv^2 = var/mean^2 = 1 (sampling sd sqrt(8/n) = {np.sqrt(8 / n_cv):.3f}")
    say(f"for n = {n_cv}). Over the {sel.sum()} bins in 20-1000 Hz:")
    say()
    say("| detector | median cv^2 | max cv^2 | expected max (H0, approx.) |")
    say("|---|---|---|---|")
    for k, d in enumerate(DETECTORS):
        say(f"| {d} | {np.median(cv2[k, sel]):.3f} | {cv2[k, sel].max():.3f} | {1 + 3.5 * np.sqrt(8 / n_cv):.3f} |")
    say()
    say("Spectral lines (average PSD > 3x its 20 Hz running median, 15-1000 Hz), with cv^2 in that bin:")
    say()
    say("| detector | lines: frequency [Hz] (height, cv^2) |")
    say("|---|---|")
    for k, d in enumerate(DETECTORS):
        r = psd_avg[k] / median_filter(psd_avg[k], 41)
        idx = np.nonzero((r > 3) & (f >= 15) & (f <= 1000))[0]
        say(f"| {d} | " + ", ".join(f"{f[i]:g} ({r[i]:.0f}x, {cv2[k, i]:.2f})" for i in idx) + " |")
    say()
    say("Reading: the band-level excess in 160-320 Hz (H1, L1) in the table above comes from the")
    say("306 Hz line dominating the Welch band average; the bin-resolved cv^2 shows no bin, line")
    say("bins included, whose power varies more than stationary Gaussian noise allows.")
    say()

    # ---------------------------------------------------------------- Gaussianity
    y = whitened_flat(neg_tr, psd_avg[None], w)
    kurt, mx = gaussianity(y)
    ysim = whitened_flat(sim[:n_sim], psd_avg[None], w)
    kurt_s, mx_s = gaussianity(ysim)
    say("## 4. Gaussianity and glitches (train negatives)")
    say()
    say("Whitened with the average PSD, band 20-1000 Hz, flat part of the window (0.1-1.9 s),")
    say("scaled to unit variance under H0. Kurtosis is excess kurtosis (0 for a Gaussian).")
    say()
    say("| detector | variance (data) | kurtosis mean (data / H0) | kurtosis sd (data / H0) | max abs y median (data / H0) | P(max abs y > 6) data | P(max abs y > 6) H0 |")
    say("|---|---|---|---|---|---|---|")
    for k, d in enumerate(DETECTORS):
        say(f"| {d} | {y[:, k].var():.4f} | {kurt[:, k].mean():+.4f} / {kurt_s[:, k].mean():+.4f} | "
            f"{kurt[:, k].std():.4f} / {kurt_s[:, k].std():.4f} | {np.median(mx[:, k]):.3f} / {np.median(mx_s[:, k]):.3f} | "
            f"{(mx[:, k] > 6).mean():.4f} | {(mx_s[:, k] > 6).mean():.4f} |")
    say()
    # frequency-domain check: |Xw|^2 / mean ~ Exp(1) per bin under H0
    from gwsciml.data.psd import whiten_fd
    Xw = whiten_fd(neg_tr[:2000], psd_avg[None], w)
    sel = (f >= 20) & (f <= 1000)
    e = (np.abs(Xw[..., sel]) ** 2) / (np.abs(Xw[..., sel]) ** 2).mean(axis=0, keepdims=True)
    ks = [stats.kstest(e[:, k].ravel()[:200000], "expon").statistic for k in range(3)]
    say("Frequency domain: whitened power per bin divided by its mean over samples should be Exp(1)")
    say("for Gaussian noise with a common PSD. KS distance against Exp(1) (200k values, sampling")
    say("level ~0.003): " + ", ".join(f"{d} {v:.4f}" for d, v in zip(DETECTORS, ks)) + ".")
    say()
    fig, ax = plt.subplots(figsize=(6, 4))
    bins = np.linspace(2.5, 8, 60)
    ax.hist(mx.ravel(), bins=bins, density=True, alpha=0.6, label="data (negatives)")
    ax.hist(mx_s.ravel(), bins=bins, density=True, alpha=0.6, label="stationary Gaussian")
    ax.set(xlabel="max |whitened strain| per sample and detector", yscale="log")
    ax.legend()
    fig.tight_layout()
    fig.savefig(figs / "p0_gaussianity.png", dpi=120)
    plt.close(fig)
    say("![Gaussianity](figures/p0_gaussianity.png)")
    say()

    # ---------------------------------------------------------------- signal power in positives
    say("## 5. Signal visibility")
    say()
    pos = xtr[ytr == 1]
    fp, Pp = welch_psd(pos)
    lpp = band_log_power(fp, Pp)
    say("Excess band power of train positives over train negatives (mean log ratio, Welch):")
    say()
    say("| detector | " + " | ".join(f"{a}-{b} Hz" for a, b in BANDS) + " |")
    say("|---|" + "---|" * len(BANDS))
    for k, d in enumerate(DETECTORS):
        say(f"| {d} | " + " | ".join(f"{(lpp[:, k, b].mean() - lp[:, k, b].mean()) * 100:+.2f} %" for b in range(len(BANDS))) + " |")
    say()
    yp = whitened_flat(pos, psd_avg[None], w)
    var_pos = (yp ** 2).mean(axis=-1)                                    # (n, 3)
    say("Per-sample whitened variance minus 1 (signal energy / noise energy in the flat window):")
    say(f"positives median {np.median(var_pos - 1):+.4f}, 99th percentile {np.percentile(var_pos - 1, 99):+.4f};")
    say(f"negatives median {np.median((y ** 2).mean(axis=-1) - 1):+.4f}. Most signals carry a tiny fraction of")
    say("the sample energy: they are invisible by eye and need a matched filter.")
    say()
    # whitened traces of the strongest positives (by excess energy in H1+L1)
    order = np.argsort(-(var_pos[:, 0] + var_pos[:, 1]))[:4]
    t = np.arange(N)[w == 1.0] * DT
    fig, axes = plt.subplots(4, 1, figsize=(10, 9), sharex=True)
    for ax, i in zip(axes, order):
        for k, d in enumerate(DETECTORS):
            ax.plot(t, yp[i, k] + 8 * (1 - k), lw=0.5, label=d)
        ax.set_ylabel(mtr[ytr == 1].id.values[i])
    axes[0].legend(loc="upper left", ncol=3)
    axes[-1].set_xlabel("time [s]")
    fig.suptitle("Whitened strain (20-1000 Hz) of the four most energetic train positives")
    fig.tight_layout()
    fig.savefig(figs / "p0_positives.png", dpi=110)
    plt.close(fig)
    say("![Strong positives](figures/p0_positives.png)")
    say()

    # ---------------------------------------------------------------- baseline
    say("## 6. Frozen baseline (old pipeline, `src/`)")
    say()
    say("| quantity | value | source |")
    say("|---|---|---|")
    say("| best val AUC, V2 fusion, no sky features | 0.874 | README.md, developer-notes.md |")
    say("| final reported run (sky FiLM, SWA) | 0.865 | README.md |")
    say("| sweep band, 100k-sample recipe, 8 configs x 3 seeds | 0.860-0.864 | SWEEP_FINDINGS.md |")
    say("| val split | rows 0-149,999 of training_labels.csv | src/model_runs.py shard split |")
    say()
    (args.out / "P0_audit.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
